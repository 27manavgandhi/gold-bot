def get_current_level(balance: float) -> dict:
    """Return level config for current balance."""
    current = LEVELS[0]
    for row in LEVELS:
        level, min_bal, lot, sl_pips, tp_pips = row
        if balance >= min_bal:
            current = row
        else:
            break
    level, min_bal, lot, sl_pips, tp_pips = current
    return {
        "level":   level,
        "lot":     lot,
        "sl_pips": sl_pips,
        "tp_pips": tp_pips,
    }
